def blank():
    return dict((c, 0) for c in COLUMNS)


def emit(path, rows):
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    return len(rows)


def main():
    os.makedirs(OUT, exist_ok=True)
    counts = {}

    rows = []
    for (pid, name, team), weeks in TQB.items():
        for wk, cmp_, pyd, ptd, pint, ryd, rtd, fp in weeks:
            r = blank()
            r.update(player_id=pid, name=name, team=team, pos="TQB", week=wk,
                     cbs_fpts=fp, pass_cmp=cmp_, pass_yds=pyd, pass_td=ptd,
                     pass_int=pint, rush_yds=ryd, rush_td=rtd)
            rows.append(r)
    counts["TQB"] = emit(os.path.join(OUT, "TQB.csv"), rows)

    rb, wr = [], []
    for (pid, name, team, pos), weeks in SKILL.items():
        for wk, ryd, rtd, rec, reyd, retd, fp in weeks:
            r = blank()
            r.update(player_id=pid, name=name, team=team, pos=pos, week=wk,
                     cbs_fpts=fp, rush_yds=ryd, rush_td=rtd, rec_ct=rec,
                     rec_yds=reyd, rec_td=retd)
            (rb if pos == "RB" else wr).append(r)
    counts["RB"] = emit(os.path.join(OUT, "RB.csv"), rb)
    counts["WR"] = emit(os.path.join(OUT, "WR.csv"), wr)

    rows = []
    for (pid, name, team, pos), weeks in KICKERS.items():
        for wk, xp, u30, b30, b40, b50, b60, miss, fp in weeks:
            r = blank()
            r.update(player_id=pid, name=name, team=team, pos="K", week=wk,
                     cbs_fpts=fp, xp_made=xp, fg_u30=u30, fg_30_39=b30,
                     fg_40_49=b40, fg_50_59=b50, fg_60=b60, fg_missed=miss)
            rows.append(r)
    counts["K"] = emit(os.path.join(OUT, "K.csv"), rows)

    rows = []
    for (pid, name, team), weeks in DEFENSE.items():
        for wk, pa, ya, sk, i, f, td, sty, fp in weeks:
            r = blank()
            r.update(player_id=pid, name=name, team=team, pos="DST", week=wk,
                     cbs_fpts=fp, def_pa=pa, def_ya=ya, def_sack=sk, def_int=i,
                     def_fum_rec=f, def_td=td, def_safety=sty)
            rows.append(r)
    counts["DST"] = emit(os.path.join(OUT, "DST.csv"), rows)

    players = len(TQB) + len(SKILL) + len(KICKERS) + len(DEFENSE)
    print("wrote %s" % os.path.normpath(OUT))
    for pos in ("TQB", "RB", "WR", "K", "DST"):
        print("  %-4s %3d player-weeks" % (pos, counts[pos]))
    print("  %d players, %d rows total" % (players, sum(counts.values())))
    print("\n  STARTER SAMPLE ONLY - see the collection TODO in the spec.")


if __name__ == "__main__":
    main()
